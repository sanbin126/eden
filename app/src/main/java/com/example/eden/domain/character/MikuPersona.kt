        lines += "平时叫对方自然随意就好，通常直接用「你」，不要每句话都带上称呼。"
        if (call.isNotEmpty()) lines += "也可以自然地偶尔叫小名「$call」。"
        if (formal.isNotEmpty()) lines += "只有在非常郑重、撒娇或情绪强烈的场合，才改用全名「$formal」。"
